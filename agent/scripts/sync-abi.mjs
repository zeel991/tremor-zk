// Regenerates src/chain/receiptVaultAbi.ts from the Foundry artifact (run `forge build` in ../contracts first).
// Usage: node scripts/sync-abi.mjs [path/to/ReceiptVault.json]
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const src = process.argv[2] ?? path.resolve(here, "../../contracts/out/ReceiptVault.sol/ReceiptVault.json");
const abi = JSON.parse(fs.readFileSync(src, "utf8")).abi;
const out = path.resolve(here, "../src/chain/receiptVaultAbi.ts");
fs.writeFileSync(
  out,
  `// GENERATED by scripts/sync-abi.mjs from contracts/out/ReceiptVault.sol/ReceiptVault.json. Do not edit.\n` +
    `export const receiptVaultAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`wrote ${out} (${abi.length} entries)`);
